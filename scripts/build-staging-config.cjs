"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const productionRef="czdrsblgwmovhoznlxvm";
const url=process.env.STAGING_SUPABASE_URL;
const key=process.env.STAGING_SUPABASE_PUBLISHABLE_KEY;
const origin=process.env.STAGING_PUBLIC_ORIGIN;
if(!url||!key||!origin)throw Error("Staging requires URL, publishable key, and public origin; refusing production fallback");
const parsed=new URL(url);
const publicOrigin=new URL(origin);
assert.equal(parsed.protocol,"https:");
assert.match(parsed.hostname,/^[a-z0-9-]+\.supabase\.co$/);
assert.notEqual(parsed.hostname,productionRef+".supabase.co","Production Supabase backend forbidden");
assert.equal(publicOrigin.protocol,"https:","Real staging URLs must use HTTPS");
assert.notEqual(publicOrigin.hostname,"calebhenry11906.github.io","Do not publish preview over production site");
assert.ok(key.startsWith("sb_publishable_"),"Only a publishable client key is allowed");
assert.ok(!/service_role|secret/i.test(key));
const payload={environment:"staging",notificationMode:"mock",supabaseUrl:parsed.origin,publishableKey:key,origin:publicOrigin.origin};
fs.writeFileSync("staging-config.js","// Generated staging-only public client configuration. Do not commit this file.\nexport const STAGING_CONFIG="+JSON.stringify(payload,null,2)+";\n");
console.log("PASS staging configuration generated for isolated project "+parsed.hostname+" (credentials not logged)");
